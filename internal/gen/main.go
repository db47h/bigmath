// Command gen generates forwarding methods for type bigmath.Float.
//
// It inspects math/big.Float's method set using go/types and writes
// float_gen.go containing forwarding wrappers that convert between
// *Float and *big.Float automatically.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

// goLicense is the BSD-style license header required for code derived from
// Go's standard library (math/big.Float method forwarding).
const goLicense = `// Copyright 2014 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE-go file.

`

// skipMethods lists methods that have hand-written implementations in
// float_format.go. The generator skips these so they can be overridden
// with optimized versions.
var skipMethods = map[string]bool{
	"Append":      true,
	"AppendText":  true,
	"Format":      true,
	"MarshalText": true,
	"String":      true,
	"Text":        true,
}

var bigFloatType = "*math/big.Float"

func main() {
	imp := importer.Default()
	pkg, err := imp.Import("math/big")
	if err != nil {
		panic(fmt.Sprintf("failed to import math/big: %v", err))
	}

	obj := pkg.Scope().Lookup("Float")
	if obj == nil {
		panic("math/big.Float type not found")
	}
	named := obj.Type().(*types.Named)

	// Collect methods and track needed imports.
	type methodInfo struct {
		Name string
		Sig  *types.Signature
	}

	var methods []methodInfo
	neededImports := map[string]bool{"math/big": true, "math": true} // always needed

	for m := range named.Methods() {
		if !m.Exported() {
			continue
		}
		sig := m.Type().(*types.Signature)
		methods = append(methods, methodInfo{Name: m.Name(), Sig: sig})
		collectImportsFromSig(sig, neededImports)
	}

	// Package-level NewFloat (constructor).
	var newFloatSig *types.Signature
	nf := pkg.Scope().Lookup("NewFloat")
	if nf != nil {
		newFloatSig = nf.Type().(*types.Signature)
		collectImportsFromSig(newFloatSig, neededImports)
	}

	// Extract doc comments from math/big source for forwarding methods.
	methodDocs, err := extractMethodDocs()
	if err != nil {
		panic(fmt.Sprintf("extracting method docs: %v", err))
	}

	// --- Generate output ---

	var buf bytes.Buffer
	buf.WriteString(goLicense)
	buf.WriteString("// Code generated by internal/gen; DO NOT EDIT.\n\n")
	buf.WriteString("package bigmath\n\n")

	writeImports(&buf, neededImports)

	slices.SortFunc(methods, func(a, b methodInfo) int {
		return strings.Compare(a.Name, b.Name)
	})
	for _, mi := range methods {
		if skipMethods[mi.Name] {
			continue
		}
		writeForwarder(&buf, mi.Name, mi.Sig, methodDocs)
	}
	if newFloatSig != nil {
		writeNewFloat(&buf, newFloatSig, methodDocs)
	}

	if err := os.WriteFile("float_gen.go", buf.Bytes(), 0o644); err != nil {
		panic(fmt.Sprintf("writing float_gen.go: %v", err))
	}
}

// writeImports writes a compact import block for the given import paths.
// aliasTypes maps qualified type names to their package-level type aliases
// emitted by writeAliases.
var aliasTypes = map[string]string{
	"math/big.Accuracy":     "Accuracy",
	"math/big.RoundingMode": "RoundingMode",
	"math/big.Word":         "Word",
}

// writeImports writes a compact import block for the given import paths.
func writeImports(w *bytes.Buffer, imports map[string]bool) {
	if len(imports) == 0 {
		return
	}
	var paths []string
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	w.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(w, "\t%q\n", p)
	}
	w.WriteString(")\n\n")
	writeAliasesAndConstants(w)
}

// writeAliasesAndConstants emits type aliases for commonly-used math/big types
// and local copies of their constants so users can write "Exact" instead of
// "big.Exact", "ToNearestEven" instead of "big.ToNearestEven", etc.
func writeAliasesAndConstants(w *bytes.Buffer) {
	w.WriteString("// Package-level type aliases for commonly-used big types.\n")
	// write aliases in a deterministic order
	aliases := make([]string, 0, len(aliasTypes))
	for _, alias := range aliasTypes {
		aliases = append(aliases, alias)
	}
	slices.Sort(aliases)
	w.WriteString("type (\n")
	for _, alias := range aliases {
		fmt.Fprintf(w, "\t%s = big.%s\n", alias, alias)
	}
	w.WriteString(")\n\n")

	// Constants for Accuracy and RoundingMode — local copies so users can
	// write "Exact" instead of "big.Exact", "ToNearestEven" instead of
	// "big.ToNearestEven", etc.
	w.WriteString("// Constants describing the Accuracy of a Float.\n")
	w.WriteString("const (\n")
	w.WriteString("\tBelow Accuracy = -1\n")
	w.WriteString("\tExact Accuracy = 0\n")
	w.WriteString("\tAbove Accuracy = +1\n")
	w.WriteString(")\n\n")

	w.WriteString("// These constants define supported rounding modes.\n")
	w.WriteString("const (\n")
	w.WriteString("\tToNearestEven RoundingMode = iota // == IEEE 754-2008 roundTiesToEven\n")
	w.WriteString("\tToNearestAway                     // == IEEE 754-2008 roundTiesToAway\n")
	w.WriteString("\tToZero                            // == IEEE 754-2008 roundTowardZero\n")
	w.WriteString("\tAwayFromZero                      // no IEEE 754-2008 equivalent\n")
	w.WriteString("\tToNegativeInf                     // == IEEE 754-2008 roundTowardNegative\n")
	w.WriteString("\tToPositiveInf                     // == IEEE 754-2008 roundTowardPositive\n")
	w.WriteString(")\n\n")

	// Exponent and precision limits — aliased from math/big to stay in sync.
	w.WriteString("// Exponent and precision limits.\n")
	w.WriteString("const (\n")
	w.WriteString("\tMaxExp  = big.MaxExp  // largest supported exponent\n")
	w.WriteString("\tMinExp  = big.MinExp  // smallest supported exponent\n")
	w.WriteString("\tMaxPrec = big.MaxPrec // largest (theoretically) supported precision; likely memory-limited\n")
	w.WriteString(")\n\n")
}

// collectImportsFromSig collects all external package paths referenced in a
// method or function signature (receiver, params, results).
func collectImportsFromSig(sig *types.Signature, imports map[string]bool) {
	if recv := sig.Recv(); recv != nil {
		collectTypeImports(recv.Type(), imports)
	}
	for v := range sig.Params().Variables() {
		collectTypeImports(v.Type(), imports)
	}
	for v := range sig.Results().Variables() {
		collectTypeImports(v.Type(), imports)
	}
}

// collectTypeImports walks a type and records all external package paths.
func collectTypeImports(t types.Type, imports map[string]bool) {
	switch t := t.(type) {
	case *types.Named:
		if pkg := t.Obj().Pkg(); pkg != nil && pkg.Path() != "" {
			imports[pkg.Path()] = true
		}
	case *types.Pointer:
		collectTypeImports(t.Elem(), imports)
	case *types.Slice:
		collectTypeImports(t.Elem(), imports)
	case *types.Array:
		collectTypeImports(t.Elem(), imports)
	case *types.Map:
		collectTypeImports(t.Key(), imports)
		collectTypeImports(t.Elem(), imports)
	case *types.Chan:
		collectTypeImports(t.Elem(), imports)
	}
}

// qname returns the qualified Go type name for t, using the package name
// (e.g. "big.Int", "big.Accuracy", "fmt.State").
func qname(t types.Type) string {
	switch t := t.(type) {
	case *types.Named:
		if pkg := t.Obj().Pkg(); pkg != nil {
			return pkg.Name() + "." + t.Obj().Name()
		}
		return t.Obj().Name()
	case *types.Pointer:
		return "*" + qname(t.Elem())
	case *types.Slice:
		return "[]" + qname(t.Elem())
	case *types.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), qname(t.Elem()))
	case *types.Basic:
		return t.Name()
	case *types.Map:
		return fmt.Sprintf("map[%s]%s", qname(t.Key()), qname(t.Elem()))
	case *types.Chan:
		return fmt.Sprintf("chan %s", qname(t.Elem()))
	case *types.Signature:
		if t.Variadic() {
			panic("variadic methods not supported")
		}
		return t.String()
	case *types.Interface:
		return t.String()
	default:
		return t.String()
	}
}

// isBigFloatPtr reports whether t is *math/big.Float.
func isBigFloatPtr(t types.Type) bool { return t.String() == bigFloatType }

// needsBigFloatConversion reports whether the generated code needs to
// convert this type between *Float and *big.Float.
func needsBigFloatConversion(t types.Type) bool {
	return isBigFloatPtr(t)
}

// genSigType returns the type name to use in the generated signature.
// *math/big.Float becomes *Float; aliased types (Accuracy, RoundingMode)
// use the short alias; everything else passes through qname.
func genSigType(t types.Type) string {
	if isBigFloatPtr(t) {
		return "*Float"
	}
	if alias, ok := aliasTypes[t.String()]; ok {
		return alias
	}
	return qname(t)
}

// writeForwarder generates a forwarding method on *Float for one *big.Float method.
func writeForwarder(w *bytes.Buffer, name string, sig *types.Signature, methodDocs map[string]string) {
	recv := sig.Recv()
	params := sig.Params()
	results := sig.Results()

	// --- Signature ---

	// Receiver: always *Float
	recvName := recv.Name()
	recvStr := fmt.Sprintf("(%s *Float)", recvName)

	// Parameters
	var paramParts []string
	var callArgs []string
	for p := range params.Variables() {
		pName := p.Name()
		if pName == "" {
			pName = "_"
		}
		ty := p.Type()
		paramParts = append(paramParts, fmt.Sprintf("%s %s", pName, genSigType(ty)))

		// Build call argument
		if needsBigFloatConversion(ty) {
			callArgs = append(callArgs, fmt.Sprintf("(*big.Float)(%s)", pName))
		} else {
			callArgs = append(callArgs, pName)
		}
	}

	// Results
	n := results.Len()
	var sigResults string
	switch n {
	case 0:
		sigResults = ""
	case 1:
		r := results.At(0)
		sigResults = " " + genSigType(r.Type())
	default:
		var resultParts []string
		for i := range n {
			r := results.At(i)
			rName := r.Name()
			if rName == "" {
				resultParts = append(resultParts, genSigType(r.Type()))
			} else {
				resultParts = append(resultParts, fmt.Sprintf("%s %s", rName, genSigType(r.Type())))
			}
		}
		sigResults = " (" + strings.Join(resultParts, ", ") + ")"
	}

	paramsStr := strings.Join(paramParts, ", ")

	// Write doc comment if available.
	if doc, ok := methodDocs[name]; ok {
		for _, line := range strings.Split(doc, "\n") {
			if line == "" {
				fmt.Fprintln(w, "//")
			} else {
				fmt.Fprintf(w, "// %s\n", line)
			}
		}
	}

	fmt.Fprintf(w, "func %s %s(%s)%s {\n\t", recvStr, name, paramsStr, sigResults)

	// --- Body ---

	// Build the inner call: (*big.Float)(receiver).Method(args...)
	callStr := fmt.Sprintf("(*big.Float)(%s).%s(%s)", recvName, name, strings.Join(callArgs, ", "))

	switch n {
	case 0:
		w.WriteString(callStr)
		w.WriteString("\n")
	case 1:
		r := results.At(0)
		if needsBigFloatConversion(r.Type()) {
			fmt.Fprintf(w, "return (*Float)(%s)", callStr)
		} else {
			fmt.Fprintf(w, "return %s", callStr)
		}
		w.WriteString("\n")
	default:
		// Multiple results: use numbered temp vars for any *big.Float results,
		// otherwise use the declared result name or generated temp name.
		var callVars []string
		var retParts []string
		for i := range n {
			r := results.At(i)
			v := fmt.Sprintf("v%d", i)
			callVars = append(callVars, v)
			if needsBigFloatConversion(r.Type()) {
				retParts = append(retParts, fmt.Sprintf("(*Float)(%s)", v))
			} else {
				retParts = append(retParts, v)
			}
		}
		fmt.Fprintf(w, "%s := %s\n\treturn %s",
			strings.Join(callVars, ", "), callStr, strings.Join(retParts, ", "))
		w.WriteString("\n")
	}

	w.WriteString("}\n\n")
}

// writeNewFloat generates a package-level NewFloat function that returns *Float.
func writeNewFloat(w *bytes.Buffer, sig *types.Signature, methodDocs map[string]string) {
	// Write doc comment if available.
	if doc, ok := methodDocs["NewFloat"]; ok {
		for _, line := range strings.Split(doc, "\n") {
			if line == "" {
				fmt.Fprintln(w, "//")
			} else {
				fmt.Fprintf(w, "// %s\n", line)
			}
		}
	}

	params := sig.Params()

	var paramParts []string
	for p := range params.Variables() {
		pName := p.Name()
		if pName == "" {
			pName = "_"
		}
		paramParts = append(paramParts, fmt.Sprintf("%s %s", pName, qname(p.Type())))
	}

	paramsStr := strings.Join(paramParts, ", ")

	fmt.Fprintf(w, "func NewFloat(%s) *Float {\n", paramsStr)
	fmt.Fprint(w, "\tif math.IsNaN(x) {\n\t\tpanic(ErrNaN(\"NewFloat(NaN)\"))\n\t}\n")
	fmt.Fprintf(w, "\treturn (*Float)(new(big.Float).SetFloat64(%s))\n", params.At(0).Name())
	fmt.Fprintf(w, "}\n")
}

// extractMethodDocs parses math/big source files and returns a map from
// method name to its doc comment text. It also captures NewFloat.
func extractMethodDocs() (map[string]string, error) {
	pkg, err := build.Default.Import("math/big", "", build.FindOnly)
	if err != nil {
		return nil, fmt.Errorf("locating math/big source: %w", err)
	}

	fset := token.NewFileSet()
	docs := make(map[string]string)

	entries, err := os.ReadDir(pkg.Dir)
	if err != nil {
		return nil, fmt.Errorf("reading math/big directory: %w", err)
	}

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		// Skip generated stringer files.
		if strings.HasSuffix(entry.Name(), "_string.go") {
			continue
		}
		// Skip platform-specific asm stubs with no Float methods.
		if entry.Name() == "arith_decl.go" || entry.Name() == "arith_decl_pure.go" {
			continue
		}

		path := filepath.Join(pkg.Dir, entry.Name())
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			continue // skip files that don't parse (e.g. platform-specific)
		}

		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || fd.Doc == nil || !fd.Name.IsExported() {
				continue
			}
			if fd.Recv != nil && len(fd.Recv.List) > 0 {
				// Method on *Float.
				star, ok := fd.Recv.List[0].Type.(*ast.StarExpr)
				if !ok {
					continue
				}
				ident, ok := star.X.(*ast.Ident)
				if !ok || ident.Name != "Float" {
					continue
				}
				docs[fd.Name.Name] = fd.Doc.Text()
			} else if fd.Name.Name == "NewFloat" {
				docs[fd.Name.Name] = fd.Doc.Text()
			}
		}
	}

	return docs, nil
}
